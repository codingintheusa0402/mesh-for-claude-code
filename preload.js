  groups: {
    set: (sid, gid) => ipcRenderer.invoke('group:set', sid, gid),
    create: (name, sids) => ipcRenderer.invoke('group:create', name, sids),
    update: (gid, patch) => ipcRenderer.invoke('group:update', gid, patch),
    remove: gid => ipcRenderer.invoke('group:delete', gid),
  },
  ollamaStatus: onPeer => ipcRenderer.invoke('ollama:status', onPeer),
  engineLog: (sid, to, by) => ipcRenderer.send('engine:log', sid, to, by),
  update: { onSave: cb => ipcRenderer.on('update:save', (_e, why) => cb(why)), saved: (state, terms) => ipcRenderer.send('update:saved', state, terms), handoff: () => ipcRenderer.invoke('update:handoff'), ready: () => ipcRenderer.send('update:ready'), rollback: () => ipcRenderer.send('update:rollback'), adopted: id => ipcRenderer.invoke('pty:adopted', id) },
  hermesInstalled: () => ipcRenderer.invoke('hermes:installed'),
  hermesHere: () => ipcRenderer.invoke('hermes:here'),
