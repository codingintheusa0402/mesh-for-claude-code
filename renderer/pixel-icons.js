const PX_GLOOT = { armour: 'pixel/gloot/item_armour_silver.png', tome: 'pixel/gloot/item_book_blue.png', gkey: 'pixel/gloot/item_key.png', gscroll: 'pixel/gloot/item_scroll_blue.png' };
const PX_ALL = () => [...Object.keys(PX_SPRITES), ...Object.keys(PX_GLOOT)];
function pixelIconURL(name, seed, reuse) {                                      // reuse > 0: the nth repeat of a picture → turned round the hue wheel
  if (PX_GLOOT[name]) return PX_GLOOT[name];
  const sp = PX_SPRITES[name] ? name : 'sword', hue = reuse ? (reuse * 137 + (PX_TINT[sp] ? pxHash(seed) % 60 : 0)) % 360 : PX_TINT[sp] ? pxHash(seed) % 360 : 0, key = sp + '|' + hue + '|' + (reuse ? 1 : 0);
  if (pxCache[key]) return pxCache[key];
  const P = PX_PAL[sp] || {}, ramp = (P.b || ['#d8dce6', '#9aa3b5', '#5d6577']).map(c => hue ? pxHue(c, hue) : c);
  const col = { k: '#14161f', w: P.w || '#ffffff', g: '#ffd65a', h: P.h || '#b07a1c', s: '#b07a1c', x: P.x || '#ff5a3c' };
  if (reuse) for (const c of ['g', 'h', 's', 'x']) col[c] = pxHue(col[c], hue);          // a repeat: the gold and accents turn too
  const cv = document.createElement('canvas'); cv.width = cv.height = 16; const x = cv.getContext('2d');
  PX_SPRITES[sp].forEach((row, y) => {
    const body = [...row].map((c, i) => c === 'b' ? i : -1).filter(i => i >= 0), first = body[0], last = body[body.length - 1];
    [...row].forEach((c, i) => {
      if (c === '.') return;
      x.fillStyle = c === 'b' ? (i === first && body.length > 2 ? ramp[0] : i === last && body.length > 2 ? ramp[2] : ramp[1]) : col[c] || '#ff00ff';
      x.fillRect(i, y, 1, 1);
    });
  });
  return (pxCache[key] = cv.toDataURL('image/png'));
}
window.pixelIconURL = pixelIconURL; window.PX_ALL = PX_ALL; window.PX_GLOOT_FILES = new Set(Object.keys(PX_GLOOT));
