// a line of a kind, mixed with the caller's own pool; {n} {mk} {item} {name} filled from vars
function probeLine(kind, extra, vars) {
  const pool = [...(PROBE_LINES[kind] || []), ...(extra || [])];
  let s = pool.length ? pool[Math.random() * pool.length | 0] : '';
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => vars[k] != null ? vars[k] : m);
  return s;
}
